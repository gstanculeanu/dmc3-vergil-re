"""A minimal Wavefront OBJ writer.

Deliberately tiny: no external dependencies, no materials beyond a ``usemtl``
name, and indices are emitted exactly as given so a caller can keep its own
vertex sharing (ASCII) or fan out per-corner vertices (SMD).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

Vec3 = Tuple[float, float, float]
Vec2 = Tuple[float, float]
Corner = Tuple[int, Optional[int], Optional[int]]  # (v, vt, vn) 1-based


def _f(value: float) -> str:
    """Compact, stable float formatting (6 decimals, no exponent noise)."""
    text = f"{value:.6f}".rstrip("0").rstrip(".")
    return text if text not in ("", "-0") else "0"


@dataclass
class ObjBuilder:
    """Accumulate vertices and named face groups, then serialise to OBJ text."""

    positions: List[Vec3] = field(default_factory=list)
    uvs: List[Vec2] = field(default_factory=list)
    normals: List[Vec3] = field(default_factory=list)
    groups: Dict[str, List[List[Corner]]] = field(default_factory=dict)

    def vertex(self, position: Vec3, uv: Optional[Vec2], normal: Optional[Vec3]) -> Corner:
        """Append a position/uv/normal and return its 1-based OBJ corner."""
        self.positions.append(position)
        v_index = len(self.positions)

        vt_index: Optional[int] = None
        if uv is not None:
            self.uvs.append(uv)
            vt_index = len(self.uvs)

        vn_index: Optional[int] = None
        if normal is not None:
            self.normals.append(normal)
            vn_index = len(self.normals)

        return (v_index, vt_index, vn_index)

    def face(self, group: str, corners: Sequence[Corner]) -> None:
        self.groups.setdefault(group, []).append(list(corners))

    @property
    def triangle_count(self) -> int:
        return sum(
            max(0, len(corners) - 2)
            for faces in self.groups.values()
            for corners in faces
        )

    def to_obj(self, object_name: str = "mesh", mtllib: Optional[str] = None) -> str:
        out: List[str] = [
            "# generated by dmc3-vergil-re tools/priorart/obj.py",
            f"# positions={len(self.positions)} uvs={len(self.uvs)} "
            f"normals={len(self.normals)} triangles={self.triangle_count}",
            f"o {object_name}",
        ]
        if mtllib:
            out.append(f"mtllib {mtllib}")

        out.extend(f"v {_f(x)} {_f(y)} {_f(z)}" for x, y, z in self.positions)
        out.extend(f"vt {_f(u)} {_f(v)}" for u, v in self.uvs)
        out.extend(f"vn {_f(x)} {_f(y)} {_f(z)}" for x, y, z in self.normals)

        for group, faces in self.groups.items():
            out.append(f"g {group}")
            out.append(f"usemtl {group}")
            for corners in faces:
                parts = []
                for v, vt, vn in corners:
                    if vt is not None and vn is not None:
                        parts.append(f"{v}/{vt}/{vn}")
                    elif vt is not None:
                        parts.append(f"{v}/{vt}")
                    elif vn is not None:
                        parts.append(f"{v}//{vn}")
                    else:
                        parts.append(f"{v}")
                out.append("f " + " ".join(parts))

        return "\n".join(out) + "\n"

    def write(self, path: str, object_name: str = "mesh", mtllib: Optional[str] = None) -> None:
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(self.to_obj(object_name=object_name, mtllib=mtllib))
